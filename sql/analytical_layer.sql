-- Read-only analytical view over the original Oracle ingestion.
-- Execute only after reviewing the existing HC_* DDL. Relative day zero = current application.
-- Aggregated payment events are not guaranteed to represent unique installments.
WITH bureau AS (
 SELECT SK_ID_CURR, COUNT(*) QTD_CREDITOS_BUREAU,
 SUM(AMT_CREDIT_SUM_DEBT) TOTAL_DIVIDA_BUREAU,
 AVG(CREDIT_DAY_OVERDUE) MEDIA_DIAS_ATRASO_BUREAU
 FROM HC_BUREAU WHERE DAYS_CREDIT <= 0 AND DAYS_CREDIT_UPDATE <= 0
 GROUP BY SK_ID_CURR
), previous AS (
 SELECT SK_ID_CURR, COUNT(*) QTD_APLICACOES_ANTERIORES,
 SUM(CASE WHEN NAME_CONTRACT_STATUS='Refused' THEN 1 ELSE 0 END) QTD_RECUSAS_ANTERIORES
 FROM HC_PREVIOUS_APPLICATION WHERE DAYS_DECISION <= 0 GROUP BY SK_ID_CURR
), installments AS (
 SELECT SK_ID_CURR, AVG(DAYS_ENTRY_PAYMENT-DAYS_INSTALMENT) ATRASO_MEDIO_PAGAMENTO,
 SUM(CASE WHEN DAYS_ENTRY_PAYMENT>DAYS_INSTALMENT THEN 1 ELSE 0 END) QTD_PARCELAS_ATRASADAS
 FROM HC_INSTALLMENTS_PAYMENTS WHERE DAYS_INSTALMENT <= 0 AND DAYS_ENTRY_PAYMENT <= 0
 GROUP BY SK_ID_CURR
)
SELECT A.SK_ID_CURR, A.TARGET, A.NAME_CONTRACT_TYPE, A.NAME_INCOME_TYPE,
A.NAME_EDUCATION_TYPE,A.NAME_HOUSING_TYPE,A.AMT_INCOME_TOTAL,A.AMT_CREDIT,
A.AMT_ANNUITY,A.AMT_GOODS_PRICE,A.DAYS_BIRTH,A.DAYS_EMPLOYED,A.CNT_CHILDREN,
A.REGION_RATING_CLIENT,A.EXT_SOURCE_1,A.EXT_SOURCE_2,A.EXT_SOURCE_3,
B.QTD_CREDITOS_BUREAU,B.TOTAL_DIVIDA_BUREAU,B.MEDIA_DIAS_ATRASO_BUREAU,
P.QTD_APLICACOES_ANTERIORES,P.QTD_RECUSAS_ANTERIORES,
I.ATRASO_MEDIO_PAGAMENTO,I.QTD_PARCELAS_ATRASADAS
FROM HC_APPLICATION A LEFT JOIN bureau B ON A.SK_ID_CURR=B.SK_ID_CURR
LEFT JOIN previous P ON A.SK_ID_CURR=P.SK_ID_CURR
LEFT JOIN installments I ON A.SK_ID_CURR=I.SK_ID_CURR
WHERE A.DATASET_TYPE='TRAIN';
